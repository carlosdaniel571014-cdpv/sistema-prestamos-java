    public void colocarDatos(){
        try {
            hist = new HistorialCrediticio(this.cliente.getIdCliente());
            txtNombre.setText(cliente.getApellidos()+", "+cliente.getNombres());
            if(hist.consultarHistorial()){
                txtIdcliente.setText(hist.getIdCliente()+"");
                if(hist.isDeudasActivas()){
                    txtDeuda.setText("SI");
                }else{
                    txtDeuda.setText("NO");
                }
                txtMonto.setText(hist.getMontoDeuda()+"");
                txtSC.setText(hist.getScoreCrediticio()+"");
                txtObs.setText(hist.getObservaciones());
            }else{
                msj.setText("No hay datos");
            }
        } catch (Exception ex) {
            msj.setText(ex.getMessage());
        }
    }
    
