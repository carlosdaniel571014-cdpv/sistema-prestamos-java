    private void btnQuitarMedioActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnQuitarMedioActionPerformed
        int filaSeleccionada = tblMedios.getSelectedRow();
        if (filaSeleccionada < 0) {
            msjTabla.setText("Selecciona un medio de la tabla para quitarlo.");
            return;
        }
        objPago.quitarMedioPorIndice(filaSeleccionada);
        modelMedios.removeRow(filaSeleccionada);
        msjTabla.setText("");

        lblTotalOperacion.setText("Total Operación: S/ " + fmt(objPago.montoTotalOperacion()));

        double faltante = objPago.montoFaltante();
        if (faltante < -0.001) {
            lblFaltante.setForeground(new java.awt.Color(200, 0, 0));
            lblFaltante.setText("Exceso de S/ " + fmt(Math.abs(faltante)) + " — quite medios registrados.");
            btnConfirmar.setEnabled(false);
        } else if (faltante <= 0.001) {
            lblFaltante.setForeground(new java.awt.Color(0, 128, 0));
            lblFaltante.setText("✔ Monto cubierto");
            btnConfirmar.setEnabled(true);
        } else {
            lblFaltante.setForeground(new java.awt.Color(200, 0, 0));
            lblFaltante.setText("Falta: S/ " + fmt(faltante));
            btnConfirmar.setEnabled(false);
        }
    }//GEN-LAST:event_btnQuitarMedioActionPerformed

