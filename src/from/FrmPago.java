    private void btnAplicarAdelantoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAplicarAdelantoActionPerformed
        double montoAd;
        try {
            montoAd = Double.parseDouble(txtMontoAdelanto.getText().trim().replace(",", "."));
        } catch (NumberFormatException e) {
            msjTabla.setText("Ingresa un monto de adelanto válido.");
            return;
        }
        if (montoAd <= 0 || montoAd > saldoCuotaAdelanto + 0.001) {
            msjTabla.setText("El adelanto debe ser mayor a 0 y no superar S/ " + fmt(saldoCuotaAdelanto) + ".");
            return;
        }
        try {
            objPago.setAdelanto(idCuotaAdelanto, nroCuotaAdelanto, montoAd);
        } catch (Exception e) {
            msjTabla.setText(e.getMessage());
            return;
        }
        lblTotalOperacion.setText("Total Operación: S/ " + fmt(objPago.montoTotalOperacion()));
        btnAplicarAdelanto.setEnabled(false);
        txtMontoAdelanto.setEnabled(false);
        btnQuitarAdelanto.setEnabled(true);
        double faltante = objPago.montoFaltante();
        if (faltante <= 0.001) {
            lblFaltante.setForeground(new java.awt.Color(0, 128, 0));
            lblFaltante.setText("✔ Monto cubierto");
            btnConfirmar.setEnabled(true);
        } else {
            lblFaltante.setForeground(new java.awt.Color(200, 0, 0));
            lblFaltante.setText("Falta: S/ " + fmt(faltante));
            btnConfirmar.setEnabled(false);
        }
        msjTabla.setText("");
    }//GEN-LAST:event_btnAplicarAdelantoActionPerformed

