        private void cargarMetodosPago() {
            catalogoMetodos.clear();
            try {
                ResultSet rs = objPago.listarMetodosPago();
                while (rs.next()) {
                    catalogoMetodos.put(rs.getString("nombre"), rs.getInt("id_metodo_pago"));
                }
                cmbMedio.setModel(new DefaultComboBoxModel<>(
                        catalogoMetodos.keySet().toArray(new String[0])));
            } catch (ADExcepcion | SQLException e) {
                msjTabla.setText("Error al cargar métodos de pago: " + e.getMessage());
            }
        }

        private void cargarCuotas() {
            modelCuotas.setRowCount(0);
            if (objPago == null) {
                return;
            }
            try {
                Mora objMora = new Mora(objPago.getIdPrestamo());
                objMora.calcularMorasPrestamo();
            } catch (Exception e) {
                msjTabla.setText("Error mora: " + e.getMessage()); // ← cambia esto
            }

            objPago.limpiarCuotas();
            objPago.limpiarMedios();
            objPago.quitarAdelanto();
            resetPanelMedios();
            resetPanelAdelanto();
            try {
                ResultSet rs = objPago.listarCuotas();
                while (rs.next()) {
                    modelCuotas.addRow(new Object[]{
                        rs.getInt("id_cuota"),
                        rs.getInt("numero_cuota"),
                        fmt(rs.getDouble("monto_cuota")),
                        fmt(rs.getDouble("saldo_pendiente")),
                        fmt(rs.getDouble("monto_mora")),
                        rs.getString("fecha_vencimiento"),
                        rs.getString("estado")
                    });
                }
                if (modelCuotas.getRowCount() == 0) {
                    msjTabla.setText("Este préstamo no tiene cuotas registradas.");
                }
            } catch (ADExcepcion | SQLException e) {
                msjTabla.setText("Error al cargar cuotas: " + e.getMessage());
            }
        }

        private void onFilaSeleccionada() {
            int[] filasSeleccionadas = tblCuotas.getSelectedRows();

            // Encontrar el número de cuota mínimo seleccionado (sin pagar)
            int nroMinSeleccionado = Integer.MAX_VALUE;
            for (int fila : filasSeleccionadas) {
                String estado = modelCuotas.getValueAt(fila, 6).toString();
                if (!estado.equals("PAGADO")) {
                    int nro = (int) modelCuotas.getValueAt(fila, 1);
                    if (nro < nroMinSeleccionado) {
                        nroMinSeleccionado = nro;
                    }
                }
            }

            // Verificar que la cuota anterior al mínimo esté pagada
            if (nroMinSeleccionado > 1 && nroMinSeleccionado < Integer.MAX_VALUE) {
                boolean anteriorPagada = false;
                for (int i = 0; i < modelCuotas.getRowCount(); i++) {
                    int nroFila = (int) modelCuotas.getValueAt(i, 1);
                    if (nroFila == nroMinSeleccionado - 1) {
                        anteriorPagada = modelCuotas.getValueAt(i, 6).toString().equals("PAGADO");
                        break;
                    }
                }
                if (!anteriorPagada) {
                    tblCuotas.clearSelection();
                    objPago.limpiarCuotas();
                    msjTabla.setText("Debe pagar primero la cuota N° " + (nroMinSeleccionado - 1) + ".");
                    actualizarResumen();
                    return;
                }
            }

            // Verificar que las cuotas seleccionadas sean consecutivas entre sí
            List<Integer> nrosSeleccionados = new ArrayList<>();
            for (int fila : filasSeleccionadas) {
                String estado = modelCuotas.getValueAt(fila, 6).toString();
                if (!estado.equals("PAGADO")) {
                    nrosSeleccionados.add((int) modelCuotas.getValueAt(fila, 1));
                }
            }
            java.util.Collections.sort(nrosSeleccionados);
            for (int i = 1; i < nrosSeleccionados.size(); i++) {
                if (nrosSeleccionados.get(i) != nrosSeleccionados.get(i - 1) + 1) {
                    tblCuotas.clearSelection();
                    objPago.limpiarCuotas();
                    msjTabla.setText("Las cuotas deben ser consecutivas. No puede saltar la cuota N° "
                            + (nrosSeleccionados.get(i - 1) + 1) + ".");
                    actualizarResumen();
                    return;
                }
            }

            // Todo válido — cargar cuotas al pago
            objPago.limpiarCuotas();
            for (int fila : filasSeleccionadas) {
                String estado = modelCuotas.getValueAt(fila, 6).toString();
                if (estado.equals("PAGADO")) {
                    continue;
                }
                int idCuota = (int) modelCuotas.getValueAt(fila, 0);
                int nroCuota = (int) modelCuotas.getValueAt(fila, 1);
                double saldo = Double.parseDouble(modelCuotas.getValueAt(fila, 3).toString().replace(",", "."));
                double mora = Double.parseDouble(modelCuotas.getValueAt(fila, 4).toString().replace(",", "."));
                objPago.agregarCuota(idCuota, nroCuota, saldo, mora);
            }

            objPago.limpiarMedios();
            objPago.quitarAdelanto();
            resetPanelMedios();
            resetPanelAdelanto();
            msjTabla.setText("");
            actualizarResumen();
        }

        private void actualizarResumen() {
            int cant = objPago.getCuotasAPagar().size();
            if (cant == 0) {
                lblResumen.setText("Sin cuotas seleccionadas.");
                lblTotal.setText("Total Cuotas: S/ 0.00");
                lblTotalOperacion.setText("Total Operación: S/ 0.00");
                pnlMedioPago.setVisible(false);
                lblCuotaAdelanto.setText("Seleccione cuotas primero.");
                txtMontoAdelanto.setEnabled(false);
                btnAplicarAdelanto.setEnabled(false);
            } else {
                lblResumen.setText(cant + " cuota(s) seleccionada(s)");
                lblTotal.setText("Total Cuotas: S/ " + fmt(objPago.totalCuotas()));
                lblTotalOperacion.setText("Total Operación: S/ " + fmt(objPago.montoTotalOperacion()));
                pnlMedioPago.setVisible(true);
                verificarSiguienteCuota();
            }
            actualizarFaltante();
        }

        private void verificarSiguienteCuota() {
            idCuotaAdelanto = -1;
            nroCuotaAdelanto = -1;
            saldoCuotaAdelanto = 0;
            if (objPago.getCuotasAPagar().isEmpty()) {
                lblCuotaAdelanto.setText("Seleccione cuotas primero.");
                txtMontoAdelanto.setEnabled(false);
                btnAplicarAdelanto.setEnabled(false);
                return;
            }
            try {
                ResultSet rs = objPago.obtenerSiguienteCuota();
                if (rs != null && rs.next()) {
                    idCuotaAdelanto = rs.getInt("id_cuota");
                    nroCuotaAdelanto = rs.getInt("numero_cuota");
                    saldoCuotaAdelanto = rs.getDouble("saldo_pendiente");
                    lblCuotaAdelanto.setText("Cuota N° " + nroCuotaAdelanto
                            + "  (Saldo: S/ " + fmt(saldoCuotaAdelanto) + ")");
                    txtMontoAdelanto.setEnabled(true);
                    btnAplicarAdelanto.setEnabled(true);
                } else {
                    lblCuotaAdelanto.setText("No hay cuota siguiente disponible.");
                    txtMontoAdelanto.setEnabled(false);
                    btnAplicarAdelanto.setEnabled(false);
                }
            } catch (ADExcepcion | SQLException e) {
                lblCuotaAdelanto.setText("Error al buscar cuota siguiente.");
                txtMontoAdelanto.setEnabled(false);
                btnAplicarAdelanto.setEnabled(false);
            }
        }

        private void actualizarFaltante() {
            if (objPago == null || objPago.getCuotasAPagar().isEmpty()) {
                lblFaltante.setText("Falta por cubrir: S/ ---");
                lblFaltante.setForeground(java.awt.Color.GRAY);
                return;
            }
            double faltante = objPago.montoFaltante();
            if (faltante <= 0.001) {
                lblFaltante.setForeground(new java.awt.Color(0, 128, 0));
                lblFaltante.setText("✔ Monto cubierto");
            } else {
                lblFaltante.setForeground(new java.awt.Color(200, 0, 0));
                lblFaltante.setText("Falta: S/ " + fmt(faltante));
            }
        }

