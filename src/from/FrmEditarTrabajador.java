private void cargarDatos() {
    try {
        Trabajador obj = new Trabajador(idTrabajador);
        obj.cargarDatos();
        txtNombres.setText(obj.getNombres());
        txtApellidos.setText(obj.getApellidos());
        txtDNI.setText(obj.getDni());
        txtEmail.setText(obj.getEmail());
        cboCargo.setSelectedItem(obj.getCargo());
    } catch (Exception e) {
        lblMensaje.setForeground(java.awt.Color.RED);
        lblMensaje.setText(e.getMessage());
    }
}

