    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
try {
        String nombres   = txtNombres.getText().trim();
        String apellidos = txtApellidos.getText().trim();
        String dni       = txtDNI.getText().trim();
        String cargo     = cboCargo.getSelectedItem().toString();
        String email     = txtEmail.getText().trim();
        String contrasena = txtContrasena.getText().trim();
        String confirmar  = txtConfirmar.getText().trim();

        Trabajador obj = new Trabajador(idTrabajador);
        obj.actualizar(nombres, apellidos, dni, cargo, email);
        
        // Si llenó contraseña, cambiarla también
        if (!contrasena.isEmpty()) {
            if (!contrasena.equals(confirmar)) {
                lblMensaje.setForeground(java.awt.Color.RED);
                lblMensaje.setText("Las contraseñas no coinciden.");
                return;
            }
            if (contrasena.length() < 6) {
                lblMensaje.setForeground(java.awt.Color.RED);
                lblMensaje.setText("La contraseña debe tener al menos 6 caracteres.");
                return;
            }
            obj.cambiarContrasena("", contrasena, confirmar);
        }

        obj.confirmarCambios();

        javax.swing.JOptionPane.showMessageDialog(this,
                "Trabajador actualizado correctamente.",
                "Éxito", javax.swing.JOptionPane.INFORMATION_MESSAGE);
        frmPadre.cargarTabla();
        this.dispose();

    } catch (Exception e) {
        lblMensaje.setForeground(java.awt.Color.RED);
        lblMensaje.setText(e.getMessage() != null ? e.getMessage() : "Error desconocido");
        e.printStackTrace();
    }

    }//GEN-LAST:event_btnActualizarActionPerformed

