    private void btnVerDetalleActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnVerDetalleActionPerformed
        int fila = tblCuotasVencidas.getSelectedRow();
        if (fila < 0) {
            lblMensaje.setText("Selecciona una cuota para ver el detalle.");
            return;
        }

        int idCuota = (int) modelMoras.getValueAt(fila, 0);
        int nroCuota = (int) modelMoras.getValueAt(fila, 1);

        try {
            objMora.cargarDetalleMora(idCuota);

            // Actualizar título
            lblTituloDetalle.setText("Detalle de Mora — Cuota N° " + nroCuota);

            // Actualizar labels con datos
            lblDias.setText(objMora.getDias() + " días");
            lblKv.setText("S/ " + fmt(objMora.getKv()));
            lblIc.setText("S/ " + fmt(objMora.getIc()));
            lblTasa.setText(Mora.TASA_MORA + "%");
            lblImora.setText("S/ " + fmt(objMora.getIMora()));
            lblIcv.setText("S/ " + fmt(objMora.getICv()));
            lblTotal.setText("S/ " + fmt(objMora.getTotal()));
            lblTotal.setForeground(new java.awt.Color(200, 0, 0));

            lblMensaje.setText("");

        } catch (ADExcepcion e) {
            JOptionPane.showMessageDialog(this,
                    "Error al obtener detalle: " + e.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnVerDetalleActionPerformed

    private void btnCalcularMorasActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularMorasActionPerformed
        if (objMora == null) {
            return;
        }
        try {
            objMora.calcularMorasPrestamo();
            cargarTablaMoras();
        } catch (Exception e) {
            lblMensaje.setText("Error: " + e.getMessage());
        }
    }//GEN-LAST:event_btnCalcularMorasActionPerformed

    private void iniciarTabla() {
        modelMoras = new DefaultTableModel(
                new String[]{"ID Cuota", "N°", "Vencimiento", "Monto Cuota",
                    "Capital", "Interés", "Días Atraso",
                    "Int. Moratorio", "Int. Comp. Mora", "Total Mora", "Estado"}, 0) {
            @Override
            public boolean isCellEditable(int r, int c) {
                return false;
            }
        };
        tblCuotasVencidas.setModel(modelMoras);
        tblCuotasVencidas.setSelectionMode(javax.swing.ListSelectionModel.SINGLE_SELECTION);
    }

    private void calcularYMostrar() {
        if (objMora == null) {
            return;
        }
        try {
            objMora.calcularMorasPrestamo();
            cargarTablaMoras();
        } catch (Exception e) {
            lblMensaje.setText("Error: " + e.getMessage());
        }
    }

    private void cargarTablaMoras() throws Exception {
        modelMoras.setRowCount(0);
        ResultSet rs = objMora.listarCuotasVencidas();
        int filas = 0;
        while (rs.next()) {
            double kv = rs.getDouble("monto_capital");
            double ic = rs.getDouble("monto_interes");
            int dias = rs.getInt("dias_mora");
            double total = rs.getDouble("monto_mora");
            double imora = Math.round(kv * ((Mora.TASA_MORA / 100.0 / 360.0) * dias) * 100.0) / 100.0;
            double icv = Math.round((total - imora) * 100.0) / 100.0;
            modelMoras.addRow(new Object[]{
                rs.getInt("id_cuota"),
                rs.getInt("numero_cuota"),
                rs.getString("fecha_vencimiento"),
                fmt(rs.getDouble("monto_cuota")),
                fmt(kv), fmt(ic), dias,
                fmt(imora), fmt(icv), fmt(total),
                rs.getString("estado_mora")
            });
            filas++;
        }
        if (filas == 0) {
            lblMensaje.setText("No hay moras registradas para este préstamo.");
        } else {
            lblMensaje.setText(filas + " mora(s) encontrada(s).");
        }
    }

    private String fmt(double v) {
        return String.format("%.2f", v);
    }

