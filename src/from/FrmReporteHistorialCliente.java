   private void cargarClientes() {
    try {
        Reporte obj = new Reporte();
        ResultSet rs = obj.obtenerListaClientes();
        cmbCliente.removeActionListener(cmbCliente.getActionListeners()[0]);
        cmbCliente.removeAllItems();
        cmbCliente.addItem("-- Seleccione un cliente --");
        while (rs.next()) {
            cmbCliente.addItem(rs.getInt("id_cliente") + " - " + rs.getString("cliente"));
        }
        cmbCliente.addActionListener(e -> cargarHistorial());
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this,
            "Error al cargar clientes:\n" + e.getMessage(),
            "Error", JOptionPane.ERROR_MESSAGE);
    }
}
    
    private void cargarHistorial() {
    if (cmbCliente.getSelectedIndex() == 0) return;

    try {
        String seleccion = cmbCliente.getSelectedItem().toString();
        int idCliente = Integer.parseInt(seleccion.split(" - ")[0]);

        Reporte obj = new Reporte();
        ResultSet rs = obj.obtenerHistorialPrestamos(idCliente);

        DefaultTableModel model = new DefaultTableModel(
            new String[]{"Préstamo N°", "Monto (S/)", "Tasa %", "Estado",
                         "Frecuencia", "Cuotas Pagadas", "Cuotas Pendientes", "Fecha Desembolso"}, 0) {
            @Override public boolean isCellEditable(int r, int c) { return false; }
        };

        NumberFormat fmt = NumberFormat.getInstance(new Locale("es", "PE"));
        fmt.setMinimumFractionDigits(2);
        fmt.setMaximumFractionDigits(2);

        int totalPrestamos   = 0;
        double montoDesembolsado = 0;

        while (rs.next()) {
            int    id       = rs.getInt("id_prestamo");
            double monto    = rs.getDouble("monto_aprobado");
            double tasa     = rs.getDouble("tasa_interes");
            String estado   = rs.getString("estado");
            String freq     = rs.getString("frecuencia_pago");
            int    pagadas  = rs.getInt("cuotas_pagadas");
            int    pend     = rs.getInt("cuotas_pendientes");
            String fecha    = rs.getString("fecha_desembolso") != null
                              ? rs.getString("fecha_desembolso") : "-";

            model.addRow(new Object[]{
                id, "S/. " + fmt.format(monto), tasa + "%",
                estado, freq, pagadas, pend, fecha
            });

            totalPrestamos++;
            if (estado.equals("DESEMBOLSADO")) montoDesembolsado += monto;
        }

        tblHistorial.setModel(model);
        lblTotalPrest.setText(String.valueOf(totalPrestamos));
        lblMontoDesemb.setText("S/. " + fmt.format(montoDesembolsado));

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this,
            "Error al cargar historial:\n" + e.getMessage(),
            "Error", JOptionPane.ERROR_MESSAGE);
    }
}
    
    
    

