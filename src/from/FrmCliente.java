    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        String dni       = txtdniCliente.getText().trim();
        String nombres   = txtNombre.getText().trim();
        String apellidos = txtApellidos.getText().trim();
        String telefono  = txtTelefono.getText().trim();
        String email     = txtEmail.getText().trim();

        if (dni.isEmpty() || nombres.isEmpty() || apellidos.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Los campos DNI, Nombres y Apellidos son obligatorios.");
            return;
        }

        if (dni.length() != 8) {
            JOptionPane.showMessageDialog(this, "El DNI debe tener exactamente 8 caracteres.");
            return;
        }

        if (!dni.matches("\\d{8}")) {
            JOptionPane.showMessageDialog(this, "El DNI debe contener solo números.");
            return;
        }

        if (!telefono.isEmpty() && !telefono.matches("\\d+")) {
            JOptionPane.showMessageDialog(this, "El teléfono debe contener solo números.");
            return;
        }

        if (!email.isEmpty() && !email.matches("^[\\w.-]+@[\\w.-]+\\.\\w{2,}$")) {
            JOptionPane.showMessageDialog(this, "El correo electrónico no es válido.");
            return;
        }

        try {
            Cliente validador = new Cliente();
            int idExcluir = modoNuevo ? -1 : this.idClienteActual;
            if (validador.existeDni(dni, idExcluir)) {
                JOptionPane.showMessageDialog(this, "Ya existe otro cliente con ese DNI.");
                return;
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
            return;
        }

        try {
            if (modoNuevo) {
                Cliente obj = new Cliente(
                        txtNombre.getText(),
                        txtApellidos.getText(),
                        dni,
                        txtTelefono.getText(),
                        txtEmail.getText(),
                        txtDireccion.getText()
                );
                obj.registrarCliente();
                JOptionPane.showMessageDialog(this, "Cliente registrado correctamente.", "Éxito", JOptionPane.INFORMATION_MESSAGE);
            } else {
                Cliente obj = new Cliente(
                        this.idClienteActual,
                        txtNombre.getText(),
                        txtApellidos.getText(),
                        dni,
                        txtTelefono.getText(),
                        txtEmail.getText(),
                        txtDireccion.getText()
                );
                obj.actualizarCliente();
                JOptionPane.showMessageDialog(this, "Cliente actualizado correctamente.", "Éxito", JOptionPane.INFORMATION_MESSAGE);
            }
            if (frmCrudCliente != null) {
                frmCrudCliente.cargarTabla();
            }
            this.dispose();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

