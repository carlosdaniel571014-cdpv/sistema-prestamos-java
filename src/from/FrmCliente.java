    public void cargarCliente(int p_idCliente) {
        try {
            Cliente obj = new Cliente();
            if (obj.buscarClientePorId(p_idCliente)) {
                txtIDCliente.setText(String.valueOf(obj.getIdCliente()));
                txtdniCliente.setText(obj.getDni());
                txtNombre.setText(obj.getNombres());
                txtApellidos.setText(obj.getApellidos());
                txtTelefono.setText(obj.getTelefono());
                txtEmail.setText(obj.getEmail());
                txtDireccion.setText(obj.getDireccion());
            } else {
                JOptionPane.showMessageDialog(this, "No se encontró el cliente.");
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }

