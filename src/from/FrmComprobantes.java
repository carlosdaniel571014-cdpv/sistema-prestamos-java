    private void btnVerComprobanteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnVerComprobanteActionPerformed
        int fila = tblComprobantes.getSelectedRow();
        if (fila < 0) {
            lblMensaje.setText("Seleccione un comprobante para verlo.");
            return;
        }
        int filaPago = tblPagos.getSelectedRow();
        if (filaPago < 0) {
            return;
        }
        int idPago = (int) modelPagos.getValueAt(filaPago, 0);
        String serie = modelComprobantes.getValueAt(fila, 0).toString();
        String tipo = modelComprobantes.getValueAt(fila, 1).toString();
        int nroCuota = (int) modelComprobantes.getValueAt(fila, 2);
        double monto = Double.parseDouble(
                modelComprobantes.getValueAt(fila, 3).toString().replace(",", "."));
        String fechaEmis = modelComprobantes.getValueAt(fila, 4).toString();

        try {
            // Cargar cabecera del pago
            ResultSet rsCab = objComprobante.obtenerCabecera(idPago);
            if (rsCab.next()) {
                lblSerie.setText(serie);
                lblFechaEmision.setText(fechaEmis);
                lblCliente.setText(rsCab.getString("cliente"));
                lblDni.setText(rsCab.getString("dni"));
                lblPrestamo.setText(String.valueOf(rsCab.getInt("id_prestamo")));
                lblTrabajador.setText(rsCab.getString("trabajador"));
                lblTipo.setText(tipo);
                lblNroCuota.setText(String.valueOf(nroCuota));
                lblObservaciones.setText(tipo.equals("PAGO_CUOTA")
                        ? "Pago cuota N° " + nroCuota
                        : "Mora cuota N° " + nroCuota);
            }

            // Cargar medios proporcionales al monto del comprobante
            ResultSet rsMedios = objComprobante.obtenerMediosPago(idPago);
            List<String[]> mediosList = new ArrayList<>();
            double totalPago = 0;
            while (rsMedios.next()) {
                String medio = rsMedios.getString("medio");
                double montoMedio = rsMedios.getDouble("monto");
                String ref = rsMedios.getString("referencia");
                totalPago += montoMedio;
                mediosList.add(new String[]{medio, String.valueOf(montoMedio), ref != null ? ref : ""});
            }
            StringBuilder sb = new StringBuilder();
            for (String[] m : mediosList) {
                double montoMedio = Double.parseDouble(m[1]);
                double proporcion = totalPago > 0 ? (monto / totalPago) * montoMedio : 0;
                sb.append(m[0]);
                if (!m[2].isEmpty()) {
                    sb.append(" (").append(m[2]).append(")");
                }
                sb.append(" ........... S/ ").append(fmt(proporcion)).append("\n");
            }
            txtAreaMedios.setText(sb.toString());

            // Calcular ITF y total
            double itf = objComprobante.calcularITF(monto);
            double total = Math.round((monto + itf) * 100.0) / 100.0;
            lblSubtotal.setText("S/ " + fmt(monto));
            lblITF.setText("S/ " + fmt(itf));
            lblTotal.setText("S/ " + fmt(total));
            lblMensaje.setText("");

        } catch (ADExcepcion | SQLException e) {
            lblMensaje.setText("Error al cargar comprobante: " + e.getMessage());
        }
    }//GEN-LAST:event_btnVerComprobanteActionPerformed

    private void btnGenerarComprobanteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerarComprobanteActionPerformed
        int[] filas = tblPagos.getSelectedRows();
        if (filas.length == 0) {
            lblMensaje.setText("Seleccione uno o más pagos para generar comprobantes.");
            return;
        }

        modelComprobantes.setRowCount(0);
        int generados = 0;

        for (int fila : filas) {
            int idPago = (int) modelPagos.getValueAt(fila, 0);

            // Si ya tiene comprobantes, solo mostrarlos sin duplicar
            if (objComprobante.tieneComprobantes(idPago)) {
                try {
                    ResultSet rs = objComprobante.listarComprobantes(idPago);
                    while (rs.next()) {
                        modelComprobantes.addRow(new Object[]{
                            rs.getString("numero_serie"),
                            rs.getString("tipo"),
                            rs.getInt("numero_cuota"),
                            fmt(rs.getDouble("monto")),
                            rs.getString("fecha_emision")
                        });
                    }
                } catch (ADExcepcion | SQLException e) {
                    lblMensaje.setText("Error al cargar comprobantes: " + e.getMessage());
                }
                continue;
            }

            // No tiene comprobantes — generarlos desde las cuotas del pago
            try {
                ResultSet rsCab = objComprobante.obtenerCabecera(idPago);
                if (!rsCab.next()) {
                    continue;
                }
                int idPrestamo = rsCab.getInt("id_prestamo");

                ResultSet rsCuotas = objComprobante.obtenerCuotasPago(idPago);
                while (rsCuotas.next()) {
                    int idCuota = rsCuotas.getInt("id_cuota");
                    int nroCuota = rsCuotas.getInt("numero_cuota");
                    double montoAb = rsCuotas.getDouble("monto_abonado");
                    boolean esAdelan = rsCuotas.getBoolean("es_adelanto");
                    double montoMora = rsCuotas.getDouble("monto_mora");
                    int idMora = rsCuotas.getInt("id_mora");
                    boolean tieneMora = !rsCuotas.wasNull() && montoMora > 0;

                    objComprobante.registrarComprobante(
                            idPrestamo, idCuota, null,
                            "PAGO_CUOTA",
                            montoAb,
                            (esAdelan ? "Adelanto" : "Pago") + " cuota N° " + nroCuota);
                    generados++;

                    if (!esAdelan && tieneMora) {
                        objComprobante.registrarComprobante(
                                idPrestamo, idCuota, idMora,
                                "PAGO_MORA",
                                montoMora,
                                "Mora cuota N° " + nroCuota);
                        generados++;
                    }
                }

                // Mostrar los comprobantes recién generados
                ResultSet rsComp = objComprobante.listarComprobantes(idPago);
                while (rsComp.next()) {
                    modelComprobantes.addRow(new Object[]{
                        rsComp.getString("numero_serie"),
                        rsComp.getString("tipo"),
                        rsComp.getInt("numero_cuota"),
                        fmt(rsComp.getDouble("monto")),
                        rsComp.getString("fecha_emision")
                    });
                }

            } catch (Exception e) {
                lblMensaje.setText("Error al generar comprobantes del pago #"
                        + idPago + ": " + e.getMessage());
                return;
            }
        }

        if (modelComprobantes.getRowCount() == 0) {
            lblMensaje.setText("No se encontraron comprobantes.");
        } else {
            lblMensaje.setText(generados > 0
                    ? generados + " comprobante(s) generado(s) correctamente."
                    : "Comprobantes cargados.");
        }
    }//GEN-LAST:event_btnGenerarComprobanteActionPerformed

