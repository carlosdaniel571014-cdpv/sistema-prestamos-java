    private void DarBajaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_DarBajaActionPerformed
        int fila = tblCliente.getSelectedRow();
        if (fila != -1) {
            String estado = tblCliente.getValueAt(fila, 7).toString();
            int idCliente = Integer.parseInt(
                    tblCliente.getValueAt(fila, 0).toString()
            );
            if ("Activo".equals(estado)) {
                int confirmacion = JOptionPane.showConfirmDialog(this,
                        "¿Está seguro que desea dar de baja al cliente?",
                        "Confirmar baja", JOptionPane.YES_NO_OPTION);
                if (confirmacion == JOptionPane.YES_OPTION) {
                    try {
                        Cliente obj = new Cliente(idCliente);
                        obj.darBajaCliente();
                        JOptionPane.showMessageDialog(this, "Cliente dado de baja correctamente.");
                        cargarTabla();
                    } catch (Exception e) {
                        JOptionPane.showMessageDialog(this, e.getMessage());
                    }
                }
            } else {
                int confirmacion = JOptionPane.showConfirmDialog(this,
                        "¿Está seguro que desea reactivar al cliente?",
                        "Confirmar alta", JOptionPane.YES_NO_OPTION);
                if (confirmacion == JOptionPane.YES_OPTION) {
                    try {
                        Cliente obj = new Cliente(idCliente);
                        obj.reactivarCliente();
                        JOptionPane.showMessageDialog(this, "Cliente reactivado correctamente.");
                        cargarTabla();
                    } catch (Exception e) {
                        JOptionPane.showMessageDialog(this, e.getMessage());
                    }
                }
            }
        } else {
            JOptionPane.showMessageDialog(this, "Debe seleccionar un cliente.");
        }
    }//GEN-LAST:event_DarBajaActionPerformed

