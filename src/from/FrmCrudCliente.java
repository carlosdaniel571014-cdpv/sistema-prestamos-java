    public void cargarTabla() {
        try {
            Cliente obj = new Cliente();
            ResultSet rs;
            if ("".equals(txtBusqueda.getText())) {
                rs = obj.listarClientes();
            } else {
                rs = obj.buscarClientes(txtBusqueda.getText());
            }
            llenarTabla(rs);
        } catch (Exception e) {
            msjError.setText(e.getMessage());
        }
    }

