    public void llenarTabla(ResultSet rs) {
        try {
            model.setRowCount(0);
            int contador = 0;
            while (rs.next()) {
                int    id         = rs.getInt("id_cliente");
                String dni        = nulo(rs.getString("dni"));
                String nombres    = rs.getString("nombres");
                String apellidos  = rs.getString("apellidos");
                String telefono   = nulo(rs.getString("telefono"));
                String email      = nulo(rs.getString("email"));
                String direccion  = nulo(rs.getString("direccion"));
                boolean activo    = rs.getBoolean("activo");
                String estado     = activo ? "Activo" : "Inactivo";
                model.addRow(new Object[]{id, dni, nombres, apellidos, telefono, email, direccion, estado});
                contador++;
            }
            txtClientesEncontrados.setText(String.valueOf(contador));
        } catch (SQLException e) {
            msjError.setText(e.getMessage());
        }
    }

    private String nulo(String v) {
        return v == null ? "sin dato" : v;
    }

